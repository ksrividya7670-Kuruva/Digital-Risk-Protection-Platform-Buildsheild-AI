"""
RiskAssessment model.

A RiskAssessment is the output of the detection engine for one Candidate
at a specific point in time. Multiple assessments can exist per candidate
(e.g. after a re-scan), but the latest one is the authoritative result.

IMPORTANT DESIGN CONSTRAINT:
  - All score fields are produced by the DETERMINISTIC detection engine.
  - The LLM explanation is stored separately and clearly labelled.
  - The LLM NEVER determines or changes the numerical scores.
  - ai_explanation is populated by AIService AFTER scoring is complete.

Score weights (configured in settings, these are the defaults):
  identity_similarity_score  : 0–25 points
  visual_similarity_score    : 0–20 points
  content_similarity_score   : 0–15 points
  link_contact_score         : 0–15 points
  anomaly_score              : 0–10 points
  evidence_score             : 0–10 points
  activity_score             : 0–5  points
  TOTAL                      : 0–100 points

Risk levels:
  80–100 → CRITICAL
  60–79  → HIGH
  40–59  → MEDIUM
  0–39   → LOW
"""

import enum
from datetime import datetime, timezone
from typing import TYPE_CHECKING, Optional

from sqlalchemy import DateTime, Enum, Float, ForeignKey, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.database import Base
from app.models.base import TimestampMixin, UUIDPrimaryKey

if TYPE_CHECKING:
    from app.models.candidate import Candidate


class RiskLevel(str, enum.Enum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class RiskAssessment(UUIDPrimaryKey, TimestampMixin, Base):
    """
    Stores the full scoring result for a Candidate.

    One Candidate may have multiple RiskAssessments over time.
    The most recent assessment (ordered by calculated_at DESC) is current.
    """

    __tablename__ = "risk_assessments"

    # ── Foreign key ───────────────────────────────────────────
    candidate_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("candidates.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    # ── Aggregate score ───────────────────────────────────────
    total_score: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        comment="Final risk score 0–100 from the deterministic detection engine",
    )
    risk_level: Mapped[RiskLevel] = mapped_column(
        Enum(RiskLevel),
        nullable=False,
        index=True,
        comment="CRITICAL(80-100) | HIGH(60-79) | MEDIUM(40-59) | LOW(0-39)",
    )
    confidence: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
        comment=(
            "Engine confidence 0.0–1.0. Low confidence when few signals fired. "
            "Does NOT affect the score — only informs the analyst."
        ),
    )

    # ── Individual signal scores ──────────────────────────────
    # Each value is the weighted contribution to the total (0.0–max_weight).
    identity_similarity_score: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
        comment="Username/name similarity contribution (max 25)",
    )
    visual_similarity_score: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
        comment="Logo/icon visual similarity contribution (max 20)",
    )
    content_similarity_score: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
        comment="Bio/description text similarity contribution (max 15)",
    )
    link_contact_score: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
        comment="Domain/link/contact risk contribution (max 15)",
    )
    anomaly_score: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
        comment="Account/app anomaly contribution (max 10)",
    )
    evidence_score: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
        comment="Reputation/evidence contribution (max 10)",
    )
    activity_score: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
        comment="Activity anomaly contribution (max 5)",
    )

    # ── Deterministic engine output ───────────────────────────
    detection_summary: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
        comment=(
            "Plain-text summary of the top signals that drove this score. "
            "Generated by the detection engine, not the LLM."
        ),
    )

    # ── AI explanation (separate from scoring) ────────────────
    ai_explanation: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
        comment=(
            "LLM-generated explanation of the finding. "
            "Populated AFTER scoring. Based only on provided evidence — "
            "never independently invented by the LLM."
        ),
    )
    ai_investigation_steps: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
        comment=(
            "LLM-generated investigation recommendations (JSON array stored as text). "
            "Advisory only — the analyst makes the final determination."
        ),
    )
    ai_generated_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        comment="Timestamp when the AI explanation was generated",
    )

    # ── Timing ────────────────────────────────────────────────
    calculated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        index=True,
        comment="When the detection engine produced this assessment",
    )

    # ── Relationship ──────────────────────────────────────────
    candidate: Mapped["Candidate"] = relationship(
        "Candidate",
        back_populates="risk_assessments",
        lazy="select",
    )

    def __repr__(self) -> str:
        return (
            f"<RiskAssessment id={self.id!r} score={self.total_score} "
            f"level={self.risk_level} candidate_id={self.candidate_id!r}>"
        )
